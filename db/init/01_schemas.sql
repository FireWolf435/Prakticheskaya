-- ============================================================================
-- Схема Service Desk PM.11 — создание схем базы данных
-- Схемы: ref, core, audit, sec, stage
-- ============================================================================

-- Закрываем схему public (доступ только через свои схемы)
REVOKE ALL ON SCHEMA public FROM PUBLIC;
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public AUTHORIZATION pg_database_owner;

-- ============================================================================
-- ref — справочники (категории, приоритеты, календарь, дежурства и т.д.)
-- ============================================================================
CREATE SCHEMA ref AUTHORIZATION pg_database_owner;

-- ============================================================================
-- core — предметная область (заявки, оборудование, пользователи, отделы)
-- ============================================================================
CREATE SCHEMA core AUTHORIZATION pg_database_owner;

-- ============================================================================
-- audit — журналы аудита (изменения, DDL, события безопасности)
-- ============================================================================
CREATE SCHEMA audit AUTHORIZATION pg_database_owner;

-- ============================================================================
-- sec — безопасность (роли, регистрация, пароли, сессии)
-- ============================================================================
CREATE SCHEMA sec AUTHORIZATION pg_database_owner;

-- ============================================================================
-- stage — staging-таблицы для загрузки исходных данных «как есть»
-- ============================================================================
CREATE SCHEMA stage AUTHORIZATION pg_database_owner;

-- Комментарии к схемам
COMMENT ON SCHEMA ref IS 'Справочники системы Service Desk';
COMMENT ON SCHEMA core IS 'Предметная область: заявки, оборудование, сотрудники, отделы';
COMMENT ON SCHEMA audit IS 'Журналы аудита изменений и событий безопасности';
COMMENT ON SCHEMA sec IS 'Безопасность: роли, привилегии, регистрация пользователей';
COMMENT ON SCHEMA stage IS 'Staging-таблицы для загрузки исходных данных';

-- ============================================================================
-- Права по умолчанию: PUBLIC не имеет доступа ни к одной схеме
-- ============================================================================
REVOKE ALL ON SCHEMA ref FROM PUBLIC;
REVOKE ALL ON SCHEMA core FROM PUBLIC;
REVOKE ALL ON SCHEMA audit FROM PUBLIC;
REVOKE ALL ON SCHEMA sec FROM PUBLIC;
REVOKE ALL ON SCHEMA stage FROM PUBLIC;
