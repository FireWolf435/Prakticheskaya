-- ============================================================================
-- Индексы (п. 4.1 ТЗ — оптимизация запросов).
--
-- НАБОР ОПРЕДЕЛЁН ЗАМЕРАМИ, А НЕ «НА ГЛАЗ»:
-- каждый индекс ниже проверен на реальном наборе 1 021 580 заявок при помощи
-- EXPLAIN (ANALYZE, BUFFERS) — результаты и отвергнутые варианты приведены
-- в docs/perf_queries_report.txt. Индексы, которые по замерам замедляли
-- запросы, в файл не включены (см. раздел «Отвергнутые варианты» в конце).
--
-- Почему индексы вообще понадобились:
--   * у core.tickets (1 млн строк) были только первичный ключ, уникальный
--     номер заявки и GIN-индекс по полнотекстовому полю — то есть ни одного
--     индекса по полям, которые стоят в WHERE и ORDER BY;
--   * у core.ticket_status_history (117 тыс. строк) не было индекса по
--     ticket_id, хотя это внешний ключ и по нему ищется история заявки;
--   * в схеме 31 внешний ключ без поддерживающего индекса: СУБД создаёт
--     индекс у родительской таблицы, но не у дочерней, поэтому ON DELETE
--     CASCADE/SET NULL и поиск дочерних строк перебирают таблицу целиком.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1. ЧАСТИЧНЫЕ СОСТАВНЫЕ ИНДЕКСЫ ПО core.tickets
--
-- Закрытых заявок 976 212 из 1 021 580 (95,6 %). Держать их в индексах
-- «текущей работы» бессмысленно, поэтому применяем частичные индексы:
-- они в десятки раз меньше полных и обслуживают только открытые заявки.
-- ---------------------------------------------------------------------------

-- Очередь оператора: открытые заявки в порядке приоритета и времени подачи.
-- Замер: 354,9 мс -> 0,29 мс, план «Parallel Seq Scan 1 млн строк» сменился
-- на «Index Scan» (прочитано 51 383 страницы -> 3). Размер 1,4 МБ.
CREATE INDEX IF NOT EXISTS idx_tickets_open_queue
    ON core.tickets (priority, created_at)
    WHERE status <> 'Закрыта';

-- Загрузка одного исполнителя — именно так считает core.auto_assign().
-- Замер: 70,7 мс -> 0,58 мс, прочитано 1 021 580 строк -> 233. Размер 336 КБ.
CREATE INDEX IF NOT EXISTS idx_tickets_executor_open
    ON core.tickets (executor_id, priority)
    WHERE status <> 'Закрыта';


-- ---------------------------------------------------------------------------
-- 2. СОСТАВНОЙ ИНДЕКС ПО core.tickets
-- ---------------------------------------------------------------------------

-- Три последние заявки по каждой категории (типовая задача «top-N в группе»).
-- Пара «категория + время по убыванию» отдаёт строки в нужном порядке — без
-- чтения всей таблицы и без сортировки.
-- Замер: 1571,4 мс -> 0,42 мс (11 последовательных сканирований по 928 871
-- строке сменились 11 индексными сканированиями по 3 строки). Размер 31 МБ.
CREATE INDEX IF NOT EXISTS idx_tickets_category_created
    ON core.tickets (category_id, created_at DESC);


-- ---------------------------------------------------------------------------
-- 3. ИНДЕКСЫ ПОД ВНЕШНИЕ КЛЮЧИ
-- ---------------------------------------------------------------------------

-- История заявки. До этого индекса поиск истории одной заявки читал все
-- 116 910 строк таблицы.
-- Замер: 14,8 мс -> 0,13 мс, «Seq Scan 116 910 строк» сменился на
-- «Index Only Scan». Размер 3,6 МБ.
CREATE INDEX IF NOT EXISTS idx_history_ticket
    ON core.ticket_status_history (ticket_id, changed_at);

-- Переходы по статусу: «все заявки, переведённые в Решена».
-- Используется аналитическим запросом 4 (просрочка, подтверждённая фактом
-- решения). Замер: 31,5 мс -> 25,6 мс (последовательное сканирование по
-- истории сменилось индексным). Размер 5 МБ.
CREATE INDEX IF NOT EXISTS idx_history_to_status
    ON core.ticket_status_history (to_status, changed_at);

-- Комментарии и вложения конкретной заявки.
CREATE INDEX IF NOT EXISTS idx_comments_ticket
    ON core.ticket_comments (ticket_id, created_at);

CREATE INDEX IF NOT EXISTS idx_attachments_ticket
    ON core.ticket_attachments (ticket_id);

-- Заявки, связанные с единицей оборудования (связь многие-ко-многим:
-- первичный ключ покрывает поиск по ticket_id, но не по asset_id).
CREATE INDEX IF NOT EXISTS idx_ticket_assets_asset
    ON core.ticket_assets (asset_id);

-- Последнее перемещение оборудования. Замер: план «вложенный цикл с
-- последовательным сканированием на каждом шаге» сменился на индексное
-- сканирование по (asset_id, moved_at DESC).
CREATE INDEX IF NOT EXISTS idx_asset_movements_asset
    ON core.asset_movements (asset_id, moved_at DESC);

-- Оборудование по местонахождению (только действующее).
CREATE INDEX IF NOT EXISTS idx_assets_location
    ON core.assets (location_id)
    WHERE is_active;


-- ---------------------------------------------------------------------------
-- 4. GIN-ИНДЕКС ПО jsonb
--
-- Журнал аудита audit.log хранит «было/стало» в jsonb. GIN-индекс позволяет
-- искать изменения по содержимому, например: кто и когда переводил заявки в
-- «Закрыта». Таблица секционирована по месяцам, индекс создаётся на всех
-- существующих секциях и автоматически наследуется новыми.
--
-- (Второй GIN-индекс — полнотекстовый по core.tickets.description_tsv —
-- создан ещё при описании таблиц, см. 04_tables_core.sql. Его замер есть в
-- docs/perf_queries_report.txt: 310,5 мс у LIKE против 71,1 мс у GIN.)
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_audit_log_new_values
    ON audit.log USING GIN (new_values);


