-- ОТВЕРГНУТЫЕ ВАРИАНТЫ (проверены замерами, в файл намеренно НЕ включены)
--
-- 1. idx_tickets_overdue (sla_deadline) WHERE status='Закрыта'
--                                          AND closed_at > sla_deadline
--    Количество просроченных заявок: 100,6 мс без индекса -> 128,4 мс с ним.
--    Причина: условие покрывает 436 837 строк — 43 % таблицы. Планировщик
--    выбирает Bitmap Heap Scan и читает почти всю таблицу вразнобой.
--    ВЫВОД: частичный индекс оправдан только при высокой избирательности.
--
-- 2. idx_tickets_closed_at (closed_at) WHERE status='Закрыта'
--    Закрытые за сентябрь 2026: 64,1 мс без индекса -> 78,4 мс с ним.
--    Причина: 95 % строк подпадают под условие.
--
-- 3. idx_tickets_created_at (created_at)
--    Заявки за сентябрь 2026: 60,7 мс без индекса -> 78,9 мс с ним.
--    Отчёт по инженерам за сентябрь: 60,1 мс -> 85,0 мс.
--    Причина: строки физически упорядочены по created_at (данные загружались
--    в хронологическом порядке), поэтому параллельное последовательное
--    сканирование читает страницы подряд, а индекс заставляет перескакивать
--    по 26 000 страниц. Для периодических отчётов индекс по дате не нужен.
--
-- 4. idx_tickets_author_created (author_id, created_at DESC) — 31 МБ.
--    Ни один запрос из 41_queries.sql по author_id не фильтрует, а сотрудники
--    из системы не удаляются (увольнение = дата в dismissal_date, не DELETE),
--    поэтому индекс под внешний ключ author_id не нужен.
--
-- Итог: из 15 проверенных индексов оставлено 11 — те, что дали измеримый
-- выигрыш. Это тоже результат оптимизации: часть индексов пришлось убрать,
-- потому что каждый лишний индекс замедляет вставку и занимает место.
-- ============================================================================
